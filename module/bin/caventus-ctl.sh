cmd_status_json() {
  load_config
  _dev=$(getprop ro.product.device 2>/dev/null || echo "oriole")
  _and=$(getprop ro.build.version.release 2>/dev/null || echo "17")
  _bld=$(getprop ro.build.display.id 2>/dev/null || echo "unknown")
