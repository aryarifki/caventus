  _ma=$(read_meminfo_kb MemAvailable); _ma=${_ma:-0}
  _ca=$(read_meminfo_kb Cached); _ca=${_ca:-0}
  _st=$(read_meminfo_kb SwapTotal); _st=${_st:-0}
